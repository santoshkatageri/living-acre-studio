#!/usr/bin/env python3
"""Stand-in X11/GL libraries so Blender's ``bpy`` module loads headless.

The ``bpy`` wheel links against the X11 and OpenGL *client* libraries. A slim
container often has none of them, and installing them needs root and network.
Background mode never opens a window or creates a GPU context, so it never
*calls* those functions — it only needs the symbols to resolve at load time.
This builds empty shared objects that export exactly the symbols the bundle
asks for, then Blender imports fine.

This is a development convenience: on a machine with a desktop, or with the
real packages installed, nothing here is used and nothing here is needed.

    python scripts/character/bpy_shim.py [/tmp/arena-bpy-libs]
"""

from __future__ import annotations

import glob
import os
import re
import subprocess
import sys

LIBS = [
    "libGL.so.1",
    "libGLX.so.0",
    "libOpenGL.so.0",
    "libXrender.so.1",
    "libXxf86vm.so.1",
    "libXfixes.so.3",
    "libXi.so.6",
    "libxkbcommon.so.0",
    "libSM.so.6",
    "libICE.so.6",
    "libdrm.so.2",
    "libgbm.so.1",
]

PREFIX = re.compile(r"^_?(gl|egl|GL|EGL|X|Xi|xkb|drm|gbm|XF86)")


def bpy_libs() -> list[str]:
    try:
        import bpy  # noqa: PLC0415 - only to locate the package

        root = os.path.dirname(bpy.__file__)
    except Exception:  # noqa: BLE001 - the point is to work when the import fails
        import importlib.util  # noqa: PLC0415

        spec = importlib.util.find_spec("bpy")
        if spec is None or not spec.origin:
            return []
        root = os.path.dirname(spec.origin)
    return glob.glob(os.path.join(root, "lib", "*.so*")) + glob.glob(os.path.join(root, "*.so"))


def collect(paths: list[str]) -> set[str]:
    if not paths:
        return set()
    out = subprocess.run(
        ["nm", "-D", "--undefined-only", *paths], capture_output=True, text=True, check=False
    ).stdout
    symbols = set()
    for line in out.splitlines():
        parts = line.split()
        if not parts:
            continue
        name = parts[-1].split("@")[0]
        if PREFIX.match(name) and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            symbols.add(name)
    return symbols


def build(directory: str, symbols: set[str]) -> None:
    os.makedirs(directory, exist_ok=True)
    source = os.path.join(directory, "stubs.c")
    lines = [
        "#include <stddef.h>",
        "/* Generated by bpy_shim.py: symbols Blender resolves but never calls",
        "   in background mode. Returning NULL is safe because no GPU context",
        "   is ever created. */",
    ]
    lines += [f"void *{name}(void) {{ return NULL; }}" for name in sorted(symbols)]
    with open(source, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    for lib in LIBS:
        subprocess.run(
            ["gcc", "-shared", "-fPIC", "-w", f"-Wl,-soname,{lib}", "-o", os.path.join(directory, lib), source],
            check=False,
        )


def main() -> int:
    directory = sys.argv[1] if len(sys.argv) > 1 else "/tmp/arena-bpy-libs"
    symbols = collect(bpy_libs())
    if not symbols:
        print("bpy_shim: no bpy bundle found — nothing to do")
        return 0
    build(directory, symbols)
    print(f"bpy_shim: {len(symbols)} symbols in {directory}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
